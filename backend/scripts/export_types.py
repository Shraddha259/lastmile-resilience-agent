"""Generate frontend/src/types.gen.ts from the Pydantic models in app/models.py.

Usage:  make types   (or: cd backend && uv run python scripts/export_types.py)
The output is committed; CI checks it is up to date.
"""

from __future__ import annotations

import sys
from enum import StrEnum
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app import models  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "frontend" / "src" / "types.gen.ts"
DOCS = [
    models.Resident,
    models.Shelter,
    models.Volunteer,
    models.Incident,
    models.Case,
    models.Checkin,
    models.Task,
    models.AgentEvent,
    models.Classification,
]


def ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts_type(x) for x in s["anyOf"]))
    if "enum" in s:
        return " | ".join(f'"{v}"' for v in s["enum"])
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        ap = s.get("additionalProperties")
        return (
            f"Record<string, {ts_type(ap)}>"
            if isinstance(ap, dict) and ap
            else ("Record<string, unknown>")
        )
    return "unknown"


def interface(name: str, schema: dict[str, Any]) -> str:
    # Fields with defaults are always present in documents the backend writes.
    props = schema.get("properties", {})
    req = set(schema.get("required", [])) | {k for k, v in props.items() if "default" in v}
    lines = [f"export interface {name} {{"]
    for prop, s in schema.get("properties", {}).items():
        opt = "" if prop in req else "?"
        lines.append(f"  {prop}{opt}: {ts_type(s)};")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    parts = [
        "// Generated by backend/scripts/export_types.py from app/models.py. Do not edit.",
        "// Timestamps arrive from Firestore as Timestamp objects; see lib/time.ts.",
        "",
    ]
    for name in dir(models):
        obj = getattr(models, name)
        if isinstance(obj, type) and issubclass(obj, StrEnum) and obj is not StrEnum:
            parts.append(f"export type {name} = " + " | ".join(f'"{m.value}"' for m in obj) + ";")
    parts.append("")
    defs: dict[str, dict[str, Any]] = {}
    for m in DOCS:
        sch = m.model_json_schema(by_alias=True, ref_template="#/$defs/{model}")
        for dn, ds in sch.pop("$defs", {}).items():
            defs[dn] = ds
        defs[m.__name__] = sch
    for dn, ds in sorted(defs.items()):
        if "enum" in ds:
            continue  # enums are emitted above
        if ds.get("type") == "object" or "properties" in ds:
            parts.append(interface(dn, ds))
            parts.append("")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(OUT.parents[2])}")


if __name__ == "__main__":
    main()
